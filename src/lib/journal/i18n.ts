export type CopyKey = Key;

export function translate(language: Language, key: CopyKey): string {
  return (language === "en" ? en : zh)[key] ?? zh[key];
}

export function moodLabel(language: Language, mood: Mood): string {
  return language === "en" ? moodsEn[mood] : moodsZh[mood];
}

export function greeting(language: Language, date = new Date()): CopyKey {
  const hour = date.getHours();
  if (hour < 5) return "greetingDawn";
  if (hour < 12) return "greetingMorning";
  if (hour < 18) return "greetingAfternoon";
  return "greetingEvening";
}
